function weave(
  current: number[],
  arr: number[],
  result: number[][],
  i = 0,
): void {
  // если длина комбинации равно исходному массиву, то процесс завершается
  if (current.length === arr.length) {
    result.push([...current]);
    return;
  }

  for (const num of arr) {
    // добавляем очередной элемент в комбинацию, если его еще нет
    if (current.indexOf(num) === -1) {
      current.push(num); // добавили первый элемент комбинации, к которому добавим остальное.
      weave(current, arr, result); // добавляем к нему оставшиеся
      current.pop(); // здесь у нас current с 1 элементом (рекурсия его не изменила) - мы удаляем ранее добавленный через push. Получается пустой массив
    }
  }
}

function permute(nums: number[]): number[][] {
  const results: number[][] = [];

  weave([], nums, results);

  return results;
}

