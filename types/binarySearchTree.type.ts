/**
 * Общий интерфейс узла бинарного дерева, используемого в бинарном поиске (BST).
 * Узел хранит значение, ссылки на родителя и детей, а также может возвращать
 * свое значение через метод getValue().
 *
 * @template T Тип значения, хранимого в узле.
 */
export interface IBinarySearchNode<T> {
  /** Значение узла. */
  value: T;

  /** Родитель текущего узла или null, если узел является корнем. */
  parent: IBinarySearchNode<T> | null;

  /** Левой дочерний узел или null. */
  leftNode: IBinarySearchNode<T> | null;

  /** Правый дочерний узел или null. */
  rightNode: IBinarySearchNode<T> | null;

  /**
   * Возвращает значение узла.
   * @returns Значение узла типа T.
   */
  getValue(): T;

  /**
   * Вставляет узел внутри дерева, начиная с этого узла.
   * Алгоритм должен корректно разместить узел слева или справа в зависимости
   * от сравнения значений.
   * @param newNode Узел, который нужно вставить в дерево.
   */
  insert(newNode: IBinarySearchNode<T>): void;

  /**
   * Удаляет дочерний узел у этого узла.
   * Удаляемый узел должен быть либо левым, либо правым ребёнком.
   * После удаления возвращает удаляемый узел, иначе null.
   * @param node Узел, который нужно удалить из дочерних.
   * @returns Удалённый узел или null, если узел не найден среди потомков.
   */
  removeChild(node: IBinarySearchNode<T>): IBinarySearchNode<T> | null;
}

/**
 * Интерфейс бинарного дерева поиска (BST).
 * Хранит корень дерева и предоставляет основной метод вставки по значению.
 *
 * @template T Тип значения, хранимого в дереве.
 */
export interface IBinarySearchTree<T> {
  /** Корневой узел дерева или null, если дерево пусто. */
  root: IBinarySearchNode<T> | null;

  /**
   * Вставляет значение в дерево согласно правилам BST.
   * Это создаёт новый узел и вставляет его в корректную позицию.
   * @param value Значение, которое нужно вставить.
   */
  insert(value: T): void;
}