/**
 * Общий интерфейс узла двусвязного списка.
 *
 * @template T Тип значения, хранимого в узле.
 */
export interface INode<T> {
  /** Значение, хранимое узлом. */
  value: T;
  /** Следующий узел в списке (или null, если узел последний). */
  next: INode<T> | null;
  /** Предыдущий узел в списке (или null, если узел первый). */
  prev: INode<T> | null;
}
/**
 * Узел двусвязного списка.
 *
 * @template T Тип значения, хранимого в узле.
 */
export class Node<T> implements INode<T> {
  public next: Node<T> | null = null;
  public prev: Node<T> | null = null;

  constructor(public value: T) {}
}
/**
 * Контракт для двусвязного списка.
 *
 * @template T Тип значения, хранимого в узлах списка.
 */
export interface IDoublyLinkedList<T> {
  /** Текущее значение головы списка, или null, если список пуст. */
  head: INode<T> | null;
  /** Текущее значение хвоста списка, или null, если список пуст. */
  tail: INode<T> | null;

  /**
   * Добавляет элемент в конец списка.
   * Время выполнения: O(1).
   * @param value Значение, которое нужно поместить в конец списка.
   */
  addEnd(value: T): void;

  /**
   * Добавляет элемент в начало списка.
   * Время выполнения: O(1).
   * @param value Значение, которое нужно поместить в начало списка.
   */
  addStart(value: T): void;

  /**
   * Удаляет элемент с конца списка.
   * Время выполнения: O(1).
   * @returns Значение удалённого элемента или null, если список пуст.
   */
  removeEnd(): T | null;

  /**
   * Удаляет элемент с начала списка.
   * Время выполнения: O(1).
   * @returns Значение удалённого элемента или null, если список пуст.
   */
  removeStart(): T | null;

  /**
   * Проверяет, пуст ли список.
   * @returns true, если список пуст; иначе false.
   */
  isEmpty(): boolean;

  /**
   * Очищает список (удаляет все элементы).
   */
  clear(): void;
}

