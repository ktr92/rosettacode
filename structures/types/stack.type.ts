/**
 * Интерфейс узла связного списка, используемого в стеке.
 *
 * @template T Тип значения, хранимого в узле.
 */
export interface INode<T> {
  /** Значение, хранимое узлом. */
  value: T;
  /** Следующий узел в списке или null, если узел последний. */
  next: INode<T> | null;
}

/**
 * Контракт стека (Last-In-First-Out).
 *
 * @template T Тип значения, хранимого в стеке.
 */
export interface IStack<T> {
  /** Головной узел стека или null, если стек пуст. */
  head: INode<T> | null;

  /**
   * Добавляет элемент в вершину стека.
   * Время выполнения: O(1).
   * @param value Значение, которое нужно поместить в стек.
   */
  add(value: T): void;

  /**
   * Удаляет и возвращает элемент из вершины стека.
   * Если стек пуст, возвращает null.
   * Время выполнения: O(1).
   * @returns Значение удалённого элемента или null, если стек пуст.
   */
  get(): T | null;

  /**
   * Возвращает значение на вершине стека без удаления.
   * @returns Значение на вершине стека или undefined, если стек пуст.
   */
  peek(): T | undefined;

  /** Очищает стек. */
  clear(): void;
}



export class Node<T> implements INode<T> {
  /** Значение узла. */
  public value: T;
  /** Следующий узел в стеке (или null, если этот узел последний). */
  public next: Node<T> | null = null;

  /**
   * Конструктор узла.
   * @param value Значение, которое хранит узел.
   */
  constructor(value: T) {
    this.value = value;
  }
}