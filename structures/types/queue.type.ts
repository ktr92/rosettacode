/**
 * Узел очереди (однонаправленный связанный список).
 *
 * @template T Тип значения, хранимого в узле.
 */
export class Node<T> {
  /** Значение узла. */
  public value: T;
  /** Следующий узел в очереди (или null, если это последний узел). */
  public next: Node<T> | null = null;

  /**
   * Конструктор узла.
   * @param value Значение, которое хранит узел.
   */
  constructor(value: T) {
    this.value = value;
  }
}

/**
 * Общий интерфейс очереди.
 * Определяет базовый контракт для очереди: добавление элемента, удаление
 * элемента и проверка пустоты.
 *
 * @template T Тип значения, хранимого в очереди.
 */
export interface IQueue<T> {
  /**
   * Добавляет элемент в конец очереди.
   * Время выполнения: O(1).
   * @param value Значение, которое нужно поставить в очередь.
   */
  enqueue(value: T): void;

  /**
   * Удаляет и возвращает элемент из головы очереди.
   * Если очередь пустая, возвращает null.
   * Время выполнения: O(1).
   * @returns Значение удалённого элемента или null, если очередь пустая.
   */
  dequeue(): T | null;

  /**
   * Проверяет, пуста ли очередь.
   * @returns true, если очередь пустая; иначе false.
   */
  isEmpty(): boolean;
}

/**
 * Базовый интерфейс узла очереди.
 * Чтобы можно было работать с любыми реализациями узла.
 *
 * @template T Тип значения, хранимого в узле.
 */
export interface INode<T> {
  value: T;
  next: INode<T> | null;
}